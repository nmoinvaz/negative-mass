def c_recip_check():
    def final(hs):
        w = og("walk", ["--fi", "0.1", "--c", "30000", "--to", "20", "--hscale", hs], "qd", "conserve")[0]
        if "stop" not in w:
            raise RuntimeError(f"the quad-double walk has no start ({w.get('class')})")
        return w["steps"], [to_mp(prs(w[k])) for k in ("F", "F1")]

    with mp.workdps(100):
        (n1, a), (n2, b) = final("1"), final("0.5")
        d = max(abs(a[0] - b[0]) / abs(a[0]), abs(a[1] - b[1]) / abs(a[1]))
    ok = d <= mp.mpf(10) ** -55
    check("recip_check", ok, f"a quad-double walk of (0.1, 3e4) to eta = 20 with every step halved ({n1} to {n2} steps) changes F and F' by a relative {mp.nstr(d, 2)} (bar 1e-55); "
          f"the control (--mutate=recip-dd, constants rounded to double-double) must exceed 1e-45")


PTS_O15 = [(0.25, 1e4), (1.0, -1e5), (2.0, 1e6), (0.1, 1e4), (0.01, 0.0), (0.005, 1e4), (0.001, -1e5), (0.05, -1e6), (5.0, 0.0), (16.0, 1e4), (64.0, -1e8), (128.0, 3e3)]


def c_step_halving():
    pts = PTS_O15 if GRID == "full" else PTS_O15[:4]
    a = og_scan(pts)
    b = og_scan(pts, extra=["--kt", "36", "--tol", "1e-38"])
    bad, worst = [], 0.0
    for k in pts:
        d = differ(a[k], b[k], 1e-10 * max(1.0, a[k]["xstar"] or 1.0), 1e-10)
        if a[k]["class"] == "SINGULAR" and b[k]["class"] == "SINGULAR":
            worst = max(worst, abs(a[k]["xstar"] - b[k]["xstar"]) / max(1.0, a[k]["xstar"]))
        if d:
            bad.append((k, d))
    check("step_halving", not bad, f"order 30, tol 1e-32 against order 36, tol 1e-38 (double-double) at {len(pts)} points: class and kind equal, eta* within 1e-10 max(1, eta*), p0 within 1e-10; "
          f"worst relative eta* difference {worst:.1e}; mismatches {len(bad)} {bad[:3]}")


