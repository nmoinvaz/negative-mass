def n_exact(terms, pt):
    f0, f1, f2, e = pt
    v = s = Fraction(0)
    for a, b, c, m, co in terms:
        t = co * f0**a * f1**b * f2**c * e**m
        v += t
        s += abs(t)
    return v, s


def c_n_table():
    pts = [(Fraction((7 * i + 3) % 23 - 11, 7), Fraction((11 * i + 5) % 29 - 14, 9), Fraction((13 * i + 7) % 31 - 15, 11),
            Fraction((17 * i + 2) % 37 - 18, 13)) for i in range(40)]
    path = os.path.join(CRATE, "target", "ntable_points_i183.txt")
    with open(path, "w") as fh:
        for p_ in pts:
            fh.write(" ".join(f"{x.numerator}/{x.denominator}" for x in p_) + "\n")
    out = og("ntable", ["--file", path])
    typed = cg.n_monomials()
    Pb = sp.Poly(cl.N_canonical(), dc.F0_, dc.F1_, dc.F2_, dc.ETA)
    built = [(a, b, c, m, Fraction(int(co.p), int(co.q))) for (a, b, c, m), co in zip(Pb.monoms(), Pb.coeffs())]
    wt = wb = Fraction(0)
    for pt, o in zip(pts, out):
        vt, st = n_exact(typed, pt)
        vb, sb = n_exact(built, pt)
        got = prs(o["n"])
        wt = max(wt, abs(got - vt) / st if st else abs(got - vt))
        wb = max(wb, abs(got - vb) / sb if sb else abs(got - vb))
    ok = len(out) == 40 and wt <= Fraction(1, 10**26) and wb <= Fraction(1, 10**26)
    check("n_table", ok, f"the lane's N (hp.rs EvalS, double-double) at 40 rational points against det_classify.conical_N() (typed): worst |dN|/sum|terms| "
          f"{float(wt):.2e}; against conical_limit.build_N() (rebuilt from D): {float(wb):.2e}; threshold 1e-26")


