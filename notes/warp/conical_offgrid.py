def parts(fr, n=8):
    out, r = [], fr
    for _ in range(n):
        f = float(r)
        out.append(f)
        r -= Fraction(f)
    return out


def mp_parts(x, n=8):
    out, r = [], x
    for _ in range(n):
        f = float(r)
        out.append(f)
        r -= mp.mpf(f)
    return out


def arr(ps):
    return "[" + ", ".join(repr(v) for v in ps) + "]"


def gen_hp_tables(g):
    Fi, a4 = cl.Fi, sp.Symbol("a4_0", real=True)
    L = ["// generated by conical_offgrid.py --gen-hp; do not edit",
         "// the series of tables.rs with every coefficient as an exact sum of 8 f64 parts (the first 2, 4 or 8 for double-,",
         "// quad- and octo-double), and ln L for the start radii L = 200 4^k",
         "pub struct SerTermHp { pub n: u8, pub j: u8, pub s: u8, pub mons: &'static [(u8, u8, [f64; 8])] }",
         f"pub const SERIES_HP_N: usize = {len(g.d)};",
         f"pub const SERIES_HP: [SerTermHp; {len(g.d)}] = ["]
    for (n, j), v in sorted(g.d.items()):
        num, den = sp.fraction(sp.together(v))
        dpoly = sp.Poly(den, Fi, a4)
        assert len(dpoly.monoms()) == 1, den
        (s, z), = dpoly.monoms()
        assert z == 0
        d = Fraction(int(dpoly.coeffs()[0]))
        npoly = sp.Poly(sp.expand(num), Fi, a4)
        mons = [(m, l, Fraction(int(c.p), int(c.q)) / d) for (m, l), c in zip(npoly.monoms(), npoly.coeffs())]
        ms = ", ".join(f"({m}, {l}, {arr(parts(c))})" for m, l, c in mons)
        L.append(f"    SerTermHp {{ n: {n}, j: {j}, s: {s}, mons: &[{ms}] }},")
    L += ["];", ""]
    mp.mp.dps = 200
    L.append(f"pub const LN_L: [[f64; 8]; {len(LS)}] = [")
    for l in LS:
        L.append(f"    {arr(mp_parts(mp.log(l)))},")
    L += ["];", ""]
    return "\n".join(L)


