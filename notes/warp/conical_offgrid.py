def main():
    t0 = time.time()
    if MUT is not None and MUT not in MUTATIONS:
        print(f"unknown mutation {MUT}")
        sys.exit(2)
    build()
    for name, fn in CHECKS:
        if not wanted(name):
            continue
        t1 = time.time()
        try:
            fn()
        except Exception as ex:  # a check that raises has failed (a mutated crate may crash)
            import traceback
            check(name, False, f"raised {type(ex).__name__}: {str(ex)[:300]}")
            if "trace" in OPTS:
                traceback.print_exc()
        print(f"  ({time.time() - t1:.0f} s)", flush=True)
    failed = [n for n, ok in RESULTS if not ok]
    print(f"\nchecks: {len(RESULTS) - len(failed)} passed, {len(failed)} failed {failed}. {time.time() - t0:.0f} s")
    if MUT is not None:
        want = MUTATIONS[MUT][0]
        print(f"control {MUT}: target checks {want}, failed {failed}")
    return failed


