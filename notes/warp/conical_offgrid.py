def cf_root(c):
    """the root eta* of h = K + 7/8 asinh(eta) + eta sqrt(eta^2 + 1)/8, K = (c - 7 ln 2 - 19/4)/8 (mpmath, bisection); h increases from K at eta = 0"""
    mp.mp.dps = 40
    k78 = mp.mpf(3) / 4 if MUT == "cf-coeff" else mp.mpf(7) / 8
    K = (mp.mpf(c) - 7 * mp.log(2) - mp.mpf(19) / 4) / 8
    h = lambda e: K + k78 * mp.asinh(e) + e * mp.sqrt(e * e + 1) / 8
    lo, hi = mp.mpf(0), mp.mpf(10) ** 6
    if h(lo) >= 0:
        return None
    for _ in range(200):
        mid = (lo + hi) / 2
        if h(mid) < 0:
            lo = mid
        else:
            hi = mid
    return float((lo + hi) / 2)


