def p0_of(v):
    return 1e-6 * v["floor"][2][1][0] if v.get("floor") and len(v["floor"]) == 3 else None


def fr(x):
    return Fraction(x[0]) + Fraction(x[1])


def prs(x):
    """a record's parts [p0, p1, ...] as an exact Fraction"""
    return sum((Fraction(p) for p in x), Fraction(0))


def to_mp(x):
    return mp.mpf(x.numerator) / x.denominator


def differ(a, b, tx, tp=None):
    """mismatch of two verdicts of the same point: None, or a description"""
    if label(a) != label(b):
        return f"{label(a)} against {label(b)}"
    if a["class"] == "SINGULAR":
        d = abs(a["xstar"] - b["xstar"])
        if not d <= tx:
            return f"eta* {a['xstar']:.12g} against {b['xstar']:.12g} (difference {d:.1e})"
    if a["class"] == "FLOOR" and tp is not None:
        pa, pb = p0_of(a), p0_of(b)
        if not (abs(pa - pb) <= tp * max(abs(pa), abs(pb))):
            return f"p0 {pa:.10e} against {pb:.10e}"
    return None


