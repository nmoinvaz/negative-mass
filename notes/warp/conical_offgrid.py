def sha12(path):
    if path not in SHA:
        SHA[path] = hashlib.sha256(open(path, "rb").read()).hexdigest()[:12]
    return SHA[path]


def run_bin(path, args, timeout=3600):
    args = [str(a) for a in args]
    key = (sha12(path), tuple(args))
    if key in CACHE:
        return CACHE[key]
    env = dict(os.environ, RAYON_NUM_THREADS="2")
    r = subprocess.run([path] + args, capture_output=True, text=True, env=env, timeout=timeout)
    if r.returncode != 0:
        raise RuntimeError(f"{os.path.basename(path)} {' '.join(args)[:300]}: exit {r.returncode}: {r.stderr[-400:]}")
    out = [json.loads(ln) for ln in r.stdout.splitlines() if ln.startswith(("{", "["))]
    CACHE[key] = out
    if DUMP:
        os.makedirs(DUMP, exist_ok=True)
        tag = hashlib.sha256(" ".join(args).encode()).hexdigest()[:10]
        with open(os.path.join(DUMP, f"{os.path.basename(path)}_{tag}.jsonl"), "w") as fh:
            fh.write(" ".join(args) + "\n")
            for o in out:
                fh.write(json.dumps(o) + "\n")
    return out


def og(cmd, extra, prec="dd", mode="conserve", mutate=True):
    args = [cmd, "--prec", prec, "--mode", mode] + list(extra)
    if mutate and MUT in OG_MUT:
        args.append(f"--mutate={MUT}")
    return run_bin(BIN, args)


def og_scan(points, prec="dd", mode="conserve", lk=0, extra=(), mutate=True):
    """{(fi, c): verdict record}, one process per F_inf"""
    by = {}
    for fi, c in points:
        by.setdefault(fi, []).append(c)
    out = {}
    for fi, cs in by.items():
        ex = ["--fi", repr(fi), "--c", ",".join(repr(c) for c in cs)] + (["--lk", lk] if lk else []) + list(extra)
        for r in og("scan", ex, prec, mode, mutate):
            out[(r["fi"], r["c"][0])] = r
    return out


