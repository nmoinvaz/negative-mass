def c_n4_factor():
    F0, F1, F2, eta = dc.F0_, dc.F1_, dc.F2_, dc.ETA
    P = sp.Poly(sp.expand(dc.conical_N()), F0, F1, F2)
    mind = min(a + b + c for (a, b, c) in P.monoms())
    low = sum(co * F0**a * F1**b * F2**c for (a, b, c), co in zip(P.monoms(), P.coeffs()) if a + b + c == mind)
    k2 = 3 if MUT == "n4-coeff" else 2
    N4 = -(eta * F2 + F1) ** 2 * ((eta**2 + 1) * (eta**2 + k2) * F1**2 + 2 * F0 * ((eta**2 + 1) * F2 + eta * F1))
    ok1 = mind == 4 and sp.expand(low - N4) == 0
    # F'/F = psi/2 in the second factor, psi = 1/chi, chi = sqrt(eta^2 + 1) h: the Bernoulli equation holds
    e, K = sp.symbols("e K", positive=True)
    h = K + sp.Rational(7, 8) * sp.asinh(e) + e * sp.sqrt(e**2 + 1) / 8
    psi = 1 / (sp.sqrt(e**2 + 1) * h)
    fac = sp.simplify(((e**2 + 1) * sp.diff(psi, e) + e * psi + (e**2 + 1) * (1 + e**2 / 4) * psi**2).rewrite(sp.log))
    Fs = sp.Function("F")
    sol = {Fs(e).diff(e, 2): Fs(e) * (sp.diff(psi, e) / 2 + psi**2 / 4), Fs(e).diff(e): Fs(e) * psi / 2}
    second = (e**2 + 1) * (e**2 + 2) * Fs(e).diff(e) ** 2 + 2 * Fs(e) * ((e**2 + 1) * Fs(e).diff(e, 2) + e * Fs(e).diff(e))
    sub = sp.simplify(second.subs({Fs(e).diff(e, 2): sol[Fs(e).diff(e, 2)]}).subs({Fs(e).diff(e): sol[Fs(e).diff(e)]}) - Fs(e) ** 2 * ((e**2 + 1) * sp.diff(psi, e) + e * psi + (e**2 + 1) * (1 + e**2 / 4) * psi**2))
    ok2 = fac == 0 and sub == 0
    check("n4_factor", ok1 and ok2, f"the lowest-degree part of N (degree {mind} in F, F', F'') equals -(eta F'' + F')^2 [(eta^2+1)(eta^2+{k2}) F'^2 + 2F((eta^2+1)F'' + eta F')] "
          f"(sympy, expanded): {ok1}; with F'/F = 1/(2 chi), chi = sqrt(eta^2+1) h, h = K + 7/8 asinh(eta) + eta sqrt(eta^2+1)/8, the second factor vanishes identically "
          f"(Bernoulli equation (eta^2+1) psi' + eta psi + (eta^2+1)(1 + eta^2/4) psi^2 = 0, sympy): {ok2}")


