NPARTS = {"dd": 2, "qd": 4, "od": 8}


def parts_of(x, n):
    out, r = [], mp.mpf(x)
    for _ in range(n):
        f = float(r)
        out.append(f)
        r -= mp.mpf(f)
    return out


def state_arg(st, n):
    return ";".join(",".join(repr(v) for v in parts_of(x, n)) for x in st)


def val(pp):
    return sum((mp.mpf(v) for v in pp[::-1]), mp.mpf(0))


XSTAR = mp.mpf(7321) / 10000


def ex_cube(x):
    F = 1 / (x - XSTAR)
    return [F, -F * F, 2 * F**3]


def ex_sqrt(x):
    F = mp.sqrt(mp.mpf(17) / 10 * (x - XSTAR))
    F1 = mp.mpf(17) / 10 / (2 * F)
    return [F, F1, -F1 * F1 / F]


def ex_lin(x):
    al, a, b = mp.mpf(7) / 10, mp.mpf(13) / 10, mp.mpf(2) / 5
    v, u = 1 + x * x, a + b * x
    return [al + u / v, b / v - 2 * x * u / v**2, -4 * x * b / v**2 - 2 * u / v**2 + 8 * x * x * u / v**3]


def c_plant_far():
    rows, ok = [], True
    for prec in ("dd", "qd"):
        with mp.workdps(120):
            n = NPARTS[prec]
            for name, exf in (("pl6", ex_cube), ("pl7", ex_sqrt)):
                recs = ll(["--poly", name, "--prec", prec, "--mode", "conserve", "--x0", "1000000", "--s0", state_arg(exf(mp.mpf(10) ** 6), n),
                           "--to", "0", "--rstop", "1e-8"])
                sg = recs[-1].get("sing")
                if sg is None:
                    ok = False
                    rows.append(f"{name} {prec}: no singularity found (stop {recs[-1]['stop']})")
                    continue
                err = abs(sg["xstar"] - float(XSTAR))
                good = err <= 1e-8 and sg["bar"] <= 1e-8 and recs[-1]["stop"] == "Singular"
                ok &= good
                rows.append(f"{name} {prec}: x* error {err:.1e}, bar {sg['bar']:.1e}, {recs[-1]['steps']} steps from 1e6")
            cps = [1e3, 10.0]
            recs = ll(["--poly", "pl4", "--prec", prec, "--mode", "conserve", "--x0", "1000000", "--s0", state_arg(ex_lin(mp.mpf(10) ** 6), n),
                       "--to", "1", "--cp", ",".join(repr(c) for c in cps)])
            errs = []
            for r in recs:
                if "cp" in r or r.get("end"):
                    x = mp.mpf(r.get("cp", r.get("x")))
                    ex = ex_lin(x)
                    errs.append(max(abs((val(r[k]) - ex[i]) / ex[i]) for i, k in enumerate(("F", "F1", "F2"))))
            bar = mp.mpf(10) ** (-24 if prec == "dd" else -50)
            worst = max(errs)
            ok &= worst <= bar and recs[-1]["stop"] == "End"
            rows.append(f"pl4 {prec}: worst relative error of F, F', F'' at 1e3, 10, 1 {mp.nstr(worst, 2)} (bar {mp.nstr(bar, 1)})")
    check("plant_far", ok, "planted equations started at x0 = 1e6 and walked inward by hp_walk with the locator: F'' = 2F^3 (pl6) and F F'' + F'^2 = 0 (pl7), "
          "x* = 0.7321, error and bar <= 1e-8; (1 + x^2) F'' + 4 x F' + 2 (F - 7/10) = 0 (pl4), exact alpha + (a + b x)/(1 + x^2): " + "; ".join(rows))


