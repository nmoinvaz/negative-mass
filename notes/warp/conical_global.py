#!/usr/bin/env python3
"""Do conical shifts u = F(x/rho) with det R_3 = 0 exist on all of eta = x/rho in R? (issue #167)

N(F, F', F''; eta) = 8 rho^6 D is det_classify.conical_N(), cubic in F''. The ends at |eta| = 200 are the series with logs of
conical_limit.md section 3; the middle is integrated by the Rust crate conical_global/ (Taylor steps of multishoot, double-double).
  A1 n_table, A2 series_residual, A3 series_stages   the equation and the series, crate against sympy and mpmath
  B1 plant_linear, B2 plant_cubic, B3 plant_blowup   planted cases through the same crate code
  C1 step_halving, C2 n_along_path, C3 independent   the integration
  D1 scan, D2 symmetry                               the grid of (F_inf, C)
  E1 bisect, E2 connect                              the family
Usage: conical_global.py [--gen] [--no-controls] [--mutate=NAME] [--only=a,b] [--logdir=DIR] [--bin=PATH]
Exit 1 if a check fails or a control does not fire."""
import json
import os
import subprocess
import sys
import time
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.join(HERE, "conical_global")
OPTS = dict(a[2:].split("=", 1) if "=" in a else (a[2:], "1") for a in sys.argv[1:] if a.startswith("--"))
MUT = OPTS.get("mutate")
ONLY = OPTS["only"].split(",") if "only" in OPTS else None

import mpmath as mp  # noqa: E402
import sympy as sp  # noqa: E402

# conical_limit parses sys.argv at import; hide ours
_argv, sys.argv = sys.argv, [sys.argv[0]]
sys.path.insert(0, HERE)
import conical_limit as cl  # noqa: E402
import det_classify as dc  # noqa: E402
sys.argv = _argv

KORD = 17  # the series is solved through eta^-KORD (amendment A1: 13 -> 17)
LEND = 200  # |eta| of the end nodes
RESULTS = []


def check(name, ok, detail):
    RESULTS.append((name, bool(ok)))
    print(f"[{'PASS' if ok else 'FAIL'}] {name}: {detail}", flush=True)


def wanted(name):
    return ONLY is None or name in ONLY


# ---------------------------------------------------------------------------------------------------------------
# tables for the crate: N as a list of monomials, the series as rational polynomials in (F_inf, C)
# ---------------------------------------------------------------------------------------------------------------
def dd_parts(fr):
    """(hi, lo) of a Fraction, as f64 literals"""
    hi = float(fr)
    lo = float(fr - Fraction(hi))
    return hi, lo


def rs_dd(fr):
    hi, lo = dd_parts(fr)
    return f"DD {{ hi: {hi!r}, lo: {lo!r} }}"


def n_monomials():
    """[(a, b, c, m, coef)] of det_classify.conical_N(), F0^a F1^b F2^c eta^m, coef an integer"""
    F0, F1, F2, eta = dc.F0_, dc.F1_, dc.F2_, dc.ETA
    P = sp.Poly(sp.expand(dc.conical_N()), F0, F1, F2, eta)
    out = []
    for (a, b, c, m), co in zip(P.monoms(), P.coeffs()):
        assert co == int(co)
        out.append((a, b, c, m, int(co)))
    return sorted(out)


def series_terms(kmax=KORD):
    """dict (n, j) -> sympy expression in (Fi, a4_0), the formal series through eta^-kmax; every stage must be solved"""
    g, log = cl.formal_series(cl.N_theta(), cl.Fi, 2, -2 * cl.Fi, kmax, cl.jlog)
    return g, log


def gen_tables(g):
    """text of src/tables.rs"""
    Fi, a4 = cl.Fi, sp.Symbol("a4_0", real=True)
    mono = n_monomials()
    L = ["// generated by conical_global.py --gen; do not edit",
         "use multidouble::dd::DD;", "",
         f"/// N = sum coef F0^a F1^b F2^c eta^m, {len(mono)} monomials of det_classify.conical_N()",
         f"pub const N_TERMS: [(u8, u8, u8, u8, i64); {len(mono)}] = ["]
    L += [f"    ({a}, {b}, {c}, {m}, {co})," for a, b, c, m, co in mono]
    L += ["];", ""]
    mp.mp.dps = 60
    ln = mp.log(LEND)
    lnf = Fraction(int(mp.floor(ln * 10**40)), 10**40)
    L += [f"pub const LEND: f64 = {float(LEND)!r};",
          f"/// ln 200 to 40 digits",
          f"pub const LN_LEND: DD = {rs_dd(lnf)};", ""]
    terms = []
    for (n, j), v in sorted(g.d.items()):
        num, den = sp.fraction(sp.together(v))
        # den = d * Fi^s
        dpoly = sp.Poly(den, Fi, a4)
        assert len(dpoly.monoms()) == 1, den
        (s, z), = dpoly.monoms()
        assert z == 0
        d = Fraction(int(dpoly.coeffs()[0]))
        npoly = sp.Poly(sp.expand(num), Fi, a4)
        mons = [(m, l, Fraction(int(c.p), int(c.q)) / d) for (m, l), c in zip(npoly.monoms(), npoly.coeffs())]
        terms.append((n, j, s, mons))
    L += [f"/// (n, j, s, [(power of F_inf, power of C, coefficient)]): a_(n,j) = sum coefficient F_inf^m C^l / F_inf^s",
          f"pub const SERIES_N: usize = {len(terms)};",
          "pub struct SerTerm { pub n: u8, pub j: u8, pub s: u8, pub mons: &'static [(u8, u8, DD)] }",
          "pub const SERIES: [SerTerm; SERIES_N] = ["]
    for n, j, s, mons in terms:
        ms = ", ".join(f"({m}, {l}, {rs_dd(c)})" for m, l, c in mons)
        L.append(f"    SerTerm {{ n: {n}, j: {j}, s: {s}, mons: &[{ms}] }},")
    L += ["];", ""]
    return "\n".join(L)


def tables_path():
    return os.path.join(CRATE, "src", "tables.rs")


def main_gen():
    g, log = series_terms()
    txt = gen_tables(g)
    with open(tables_path(), "w") as fh:
        fh.write(txt)
    print(f"wrote {tables_path()}: {len(g.d)} series terms, {len(n_monomials())} monomials of N")


if __name__ == "__main__" and "gen" in OPTS:
    main_gen()
    sys.exit(0)
