"""Compiled coefficient functions for modes_general.py and modes_complex.py: the master equation's A2, A1, A0 and the
areal radius r with its z-derivatives, as numba functions of complex arguments, from the same sympy expressions as
modes_general.coefficient_functions and end_functions.

The expressions are reduced by common-subexpression elimination (sympy.cse) and printed as Python source into
_fastcoef_gen.py (next to this file; regenerated when master_general.py or derive_general.py, which define them,
or this file change), which numba compiles on first use and caches (cache=True). The values are the same functions
evaluated in double precision with a different order of operations, so they agree with the lambdified ones to
rounding (fast_check.py).

    coef_x(x, n, c, g1, e2, W) -> (A2, A1, A0)                   at y = x (complex), for the Frobenius step
    end_L / end_R(z, n, c, g1, e2, W) -> (A2, A1, A0, r_z, r_zz)  at y = side (pi/2 - z), side = -1 / +1
    r_L / r_R(z, n, c, g1, e2) -> (r, r_z, r_zz)
    rhs_L / rhs_R(t, psi, th, n, c, g1, e2, W) -> (dpsi/dt, dth/dt)   Wormhole.shoot's amplitude-phase system in
                                                                        t = log z
    lin_L / lin_R(z, n, c, g1, e2, W) -> the 2 x 2 matrix z M(z) of modes_complex.ComplexWormhole.system
All arguments may be complex (e2 is passed complex: Lam = sqrt(g1^2 - e2) is imaginary when e2 > g1^2).
"""
import hashlib
import importlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "_fastcoef_gen.py")
SOURCES = ("master_general.py", "derive_general.py", "fastcoef.py")


def _digest():
    h = hashlib.sha256()
    for f in SOURCES:
        with open(os.path.join(HERE, f), "rb") as fh:
            h.update(fh.read())
    return h.hexdigest()[:16]


def _fun(name, args, exprs, printer):
    import sympy as sp
    reps, red = sp.cse(exprs, symbols=sp.numbered_symbols("t_"), optimizations="basic")
    lines = ["@numba.njit(cache=True, fastmath=False)", f"def {name}({', '.join(args)}):"]
    for s, e in reps:
        lines.append(f"    {s} = {printer.doprint(e)}")
    lines.append("    return (" + ", ".join(printer.doprint(e) for e in red) + ",)")
    return "\n".join(lines) + "\n"


def generate():
    import sympy as sp
    from sympy.printing.numpy import NumPyPrinter

    import derive_general as d
    import master_general as mg
    a2, a1, a0, *_ = mg.master_coeffs()
    nu, lam, r, P, qq = mg.background_exprs()
    bg = {d.nu0: nu, d.lam0: lam, d.r0: r, d.P: P, d.q: qq}
    exprs = [sp.together(v.subs(bg).doit()) for v in (a2, a1, a0)]
    xs, zs = sp.Symbol("x"), sp.Symbol("z", positive=True)
    nn, cc, gg, ee, WW = sp.symbols("n c g1 e2 W")
    names = {d.x: xs, mg.n: nn, mg.c: cc, mg.g1: gg, mg.e2: ee, d.W: WW}
    pr = NumPyPrinter({"fully_qualified_modules": True, "inline": True, "allow_unknown_functions": False})
    out = [f"# generated by fastcoef.py from master_general.py and derive_general.py (digest {_digest()}); do not edit",
           "import numba", "import numpy", ""]
    out.append(_fun("coef_x", ["x", "n", "c", "g1", "e2", "W"], [e.subs(names) for e in exprs], pr))
    for side, tag in ((-1, "L"), (1, "R")):
        sub = {d.x: side * (sp.pi / 2 - zs)}
        ez = [e.subs(sub).subs(names) for e in exprs]
        rz = r.subs(sub)
        rd = [rz, sp.diff(rz, zs), sp.diff(rz, zs, 2)]
        rd = [e.subs(names) for e in rd]
        out.append(_fun(f"end_{tag}", ["z", "n", "c", "g1", "e2", "W"], ez + rd[1:], pr))
        out.append(_fun(f"r_{tag}", ["z", "n", "c", "g1", "e2"], rd, pr))
        out.append(f'''@numba.njit(cache=True)
def rhs_{tag}(t, psi, th, n, c, g1, e2, W):
    zz = numpy.exp(t)
    A2, A1, A0, rz, rzz = end_{tag}(zz + 0j, n, c, g1, e2, W)
    A2, A1, A0, rz, rzz = A2.real, A1.real, A0.real, rz.real, rzz.real
    g2 = 1.0 + rz * rz
    g = numpy.sqrt(g2)
    co, sn = numpy.cos(th), numpy.sin(th)
    a = -({side}) * g * sn
    b = (({side}) * A1 / A2 - rz * rzz / g2) * sn + ({side}) * A0 * co / (A2 * g)
    return zz * (co * a + sn * b), zz * (co * b - sn * a)


@numba.njit(cache=True)
def lin_{tag}(z, n, c, g1, e2, W):
    A2, A1, A0, rz, rzz = end_{tag}(z + 0j, n, c, g1, e2, W)
    rz, rzz = rz.real, rzz.real
    g2 = 1.0 + rz * rz
    g = numpy.sqrt(g2)
    m = numpy.zeros((2, 2), dtype=numpy.complex128)
    m[0, 1] = -({side}) * g * z
    m[1, 0] = ({side}) * A0 / (A2 * g) * z
    m[1, 1] = (({side}) * A1 / A2 - rz * rzz / g2) * z
    return m
''')
    src = "\n\n".join(out)
    tmp = GEN + ".tmp"
    with open(tmp, "w") as fh:
        fh.write(src)
    os.replace(tmp, GEN)


def load():
    """the generated module, regenerated first if its sources changed"""
    dig = _digest()
    ok = False
    if os.path.exists(GEN):
        with open(GEN) as fh:
            ok = f"(digest {dig})" in fh.readline()
    if not ok:
        generate()
    if HERE not in sys.path:
        sys.path.insert(0, HERE)
    if "_fastcoef_gen" in sys.modules and ok:
        return sys.modules["_fastcoef_gen"]
    return importlib.import_module("_fastcoef_gen") if ok else importlib.reload(importlib.import_module("_fastcoef_gen"))


if __name__ == "__main__":
    import time
    t = time.time()
    generate()
    print(f"wrote {GEN} ({os.path.getsize(GEN)} bytes) in {time.time() - t:.1f} s")
